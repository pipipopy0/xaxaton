from logger_config import logger



def get_text(db, key: str,   max_id: str = None, **kwargs) -> str:
    language = "ru"
    
    try:
        if db and max_id != None:
            user_id = str(max_id)
            user = db.select_data("users", where_conditions={"user_id" : user_id})
            if user and user[0][6]:
                language = user[0][6]

        if language not in ["ru", "en"]:
            language = "ru"
            logger.warning(f"User {max_id} has unsupported language '{language}', defaulting to 'ru'.")
    
        text = TEXTS.get(key, {}).get(language, "")
        if kwargs and text:
            try:
                text = text.format(**kwargs)
            except Exception as e:
                logger.warning(f"Failed to format text '{key}': {e}")

        return text
    
    except Exception as e:
        logger.error(f"Error retrieving text for key '{key}' and language '{language}': {e}")
        return ""